const { chromium } = require('playwright');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  try {
    const page = await browser.newPage();
    await page.addInitScript(() => localStorage.setItem('codex-desktop-state-v1', JSON.stringify({ activeThreadId: 'a', threads: [{ id: 'a', title: 'Original', messages: [], status: 'completed', updatedAt: '' }] })));
    await page.goto(process.env.FELIX_TEST_URL || 'http://127.0.0.1:5318');
    const input = page.getByRole('textbox', { name: '消息', exact: true });
    await input.fill('Retain original draft');
    await page.keyboard.press('Control+Shift+O');
    await page.waitForFunction(() => JSON.parse(localStorage.getItem('codex-desktop-state-v1')).threads.length === 2);
    assert.equal(await input.inputValue(), '');
    await page.waitForFunction(() => document.activeElement?.getAttribute('aria-label') === '消息');
    await page.getByRole('button', { name: 'Original', exact: true }).click();
    assert.equal(await input.inputValue(), 'Retain original draft');
    await page.keyboard.press('Control+p');
    const fileSearch = page.getByRole('textbox', { name: '查找工作区文件', exact: true });
    await fileSearch.waitFor();
    await page.waitForFunction(() => document.activeElement?.getAttribute('aria-label') === '查找工作区文件');
    await fileSearch.fill('keep query');
    await input.focus(); await page.keyboard.press('Control+p');
    await page.waitForFunction(() => document.activeElement?.getAttribute('aria-label') === '查找工作区文件');
    assert.equal(await fileSearch.inputValue(), 'keep query');
    assert.equal(await input.inputValue(), 'Retain original draft');
    await page.getByRole('button', { name: '关闭文件面板', exact: true }).click();
    await page.getByRole('button', { name: '收起侧栏', exact: true }).click();
    await page.keyboard.press('Control+k');
    const search = page.getByRole('textbox', { name: '搜索最近会话', exact: true });
    await search.waitFor(); await page.waitForFunction(() => document.activeElement?.id === 'sidebar-search');
    await page.keyboard.press('Control+Shift+L');
    await page.waitForFunction(() => document.activeElement?.getAttribute('aria-label') === '消息');
    await page.evaluate(() => document.dispatchEvent(new KeyboardEvent('keydown', { key: 'O', ctrlKey: true, shiftKey: true, isComposing: true, bubbles: true })));
    assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('codex-desktop-state-v1')).threads.length), 2);
    await page.getByRole('button', { name: '归档会话', exact: true }).click();
    await page.getByRole('dialog').waitFor();
    await page.keyboard.press('Control+p');
    assert.equal(await fileSearch.count(), 0);
    await page.keyboard.press('Control+Shift+O');
    assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('codex-desktop-state-v1')).threads.length), 2);
    await page.getByRole('button', { name: '关闭归档会话', exact: true }).click();
    await page.evaluate(() => {
      const terminal = document.createElement('div'); terminal.className = 'xterm'; document.body.append(terminal);
      terminal.dispatchEvent(new KeyboardEvent('keydown', { key: 'O', ctrlKey: true, shiftKey: true, bubbles: true }));
      terminal.dispatchEvent(new KeyboardEvent('keydown', { key: 'p', ctrlKey: true, bubbles: true }));
      terminal.remove();
      document.dispatchEvent(new KeyboardEvent('keydown', { key: 'O', ctrlKey: true, shiftKey: true, repeat: true, bubbles: true }));
      document.dispatchEvent(new KeyboardEvent('keydown', { key: 'p', ctrlKey: true, isComposing: true, bubbles: true }));
    });
    assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('codex-desktop-state-v1')).threads.length), 2);
    assert.equal(await fileSearch.count(), 0);
    console.log('PASS: new conversation, draft retention, hidden sidebar search, composer focus and IME guard');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
