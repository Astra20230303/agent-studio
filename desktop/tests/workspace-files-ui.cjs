const { chromium } = require('playwright');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  try {
    const page = await browser.newPage();
    await page.addInitScript(() => {
      localStorage.setItem('codex-desktop-state-v1', JSON.stringify({ model: 'test', activeProjectId: 'p', projects: [{ id: 'p', path: 'D:/Project', name: 'Project', git: {} }], threads: [] }));
      window.__reads = [];
      window.desktop = { listModels: async () => ({ ok: true, models: ['test'] }), providerStatus: async () => ({ keyConfigured: true }), workspaceFile: async input => {
        window.__reads.push(input);
        if (input.action === 'search-content') return {ok:true,result:{entries:[{name:'example.ts',path:'src/example.ts',directory:false,revision:'before',line:2,column:1,snippet:'File content'}]}};
        if (input.action === 'search') return { ok: true, result: { entries: input.query === 'example' ? [{ name: 'example.ts', path: 'src/example.ts', directory: false }] : [] } };
        return { ok: true, result: input.action === 'read' ? { revision:window.__changedFile?'after':'before', text: '<script>never execute</script>\nFile content', truncated: true } : { entries: input.path === '.' ? [{ name: 'src', path: 'src', directory: true }] : [{ name: 'example.ts', path: 'src/example.ts', directory: false }] } };
      } };
      window.codex = { connect: async () => ({ ok: true }), request: async () => ({ ok: true, result: { data: [] } }), notify: async () => ({}), onNotification: () => () => {}, onClosed: () => () => {}, onError: () => () => {}, onStderr: () => () => {}, onServerRequest: () => () => {} };
    });
    await page.goto(process.env.FELIX_TEST_URL || 'http://127.0.0.1:5318');
    await page.getByRole('button', { name: '浏览工作区文件', exact: true }).click();
    await page.getByRole('button', { name: '▸ src', exact: true }).click();
    await page.getByRole('button', { name: '▧ example.ts', exact: true }).click();
    await page.getByText('仅预览前 256 KB。', { exact: true }).waitFor();
    assert.match(await page.locator('.workspace-files pre').innerText(), /<script>/);
    const expand = page.getByRole('button', { name: '展开文件预览', exact: true });
    await expand.click();
    const dialog = page.getByRole('dialog', { name: '消息文件预览', exact: true });
    await dialog.locator('pre').getByText('File content', { exact: true }).waitFor();
    await dialog.getByRole('button', { name: '查找预览内容', exact: true }).click();
    await dialog.getByRole('textbox', { name: '查找预览内容', exact: true }).fill('File');
    await dialog.getByRole('status').filter({ hasText: '1 / 1 处匹配' }).waitFor();
    await dialog.getByRole('button', { name: '关闭预览', exact: true }).click();
    assert.ok(await expand.evaluate(element => element === document.activeElement));
    await page.getByRole('button', { name: '添加到消息', exact: true }).click();
    await page.getByRole('button', { name: '移除附件：D:/Project/src/example.ts', exact: true }).waitFor();
    await page.getByRole('button', { name: '返回目录', exact: true }).click();
    await page.getByRole('button', { name: '上级目录', exact: true }).click();
    await page.getByRole('button', { name: '▸ src', exact: true }).waitFor();
    await page.getByRole('textbox', { name: '查找工作区文件' }).fill('example');
    await page.getByRole('button', { name: '查找文件', exact: true }).click();
    await page.getByRole('button', { name: '▧ src/example.ts', exact: true }).click();
    await page.getByText('仅预览前 256 KB。', { exact: true }).waitFor();
    await page.getByRole('button', { name: '返回目录', exact: true }).click();
    await page.getByRole('button', { name: '▧ src/example.ts', exact: true }).waitFor();
    await page.getByRole('textbox', { name: '查找工作区文件' }).fill('missing');
    await page.getByRole('button', { name: '查找文件', exact: true }).click();
    await page.getByText('没有匹配文件。', { exact: true }).waitFor();
    await page.getByRole('button', { name: '清除文件查找', exact: true }).click();
    await page.getByRole('button', { name: '▸ src', exact: true }).waitFor();
    await page.getByRole('combobox',{name:'文件搜索方式'}).selectOption('content');
    await page.getByRole('textbox',{name:'查找工作区文件'}).fill('File');
    await page.getByRole('button',{name:'查找文件',exact:true}).click();
    await page.getByRole('button',{name:'▧ src/example.ts:2:1 · File content',exact:true}).click();
    await page.locator('.workspace-files pre span').filter({hasText:'File content'}).waitFor();
    assert.ok(await page.locator('.workspace-files pre span').filter({hasText:'File content'}).getAttribute('style'));
    await expand.click();
    await dialog.locator('pre [aria-current="location"]').waitFor();
    assert.equal(await dialog.locator('pre [aria-current="location"]').getAttribute('data-line'), '2');
    await dialog.getByRole('button', { name: '关闭预览', exact: true }).click();
    await page.getByRole('button',{name:'返回目录',exact:true}).click();
    await page.evaluate(()=>{window.__changedFile=true;});
    await page.getByRole('button',{name:'▧ src/example.ts:2:1 · File content',exact:true}).click();
    await page.getByText('文件在搜索后已变化，请返回并刷新搜索结果。',{exact:true}).waitFor();
    assert.equal(await page.locator('.workspace-files pre span').count(),0);
    await expand.click();
    await dialog.locator('pre').waitFor();
    assert.equal(await dialog.locator('pre [aria-current="location"]').count(), 0);
    await dialog.getByRole('button', { name: '关闭预览', exact: true }).click();
    assert.ok((await page.evaluate(() => window.__reads)).every(item => item.root === 'D:/Project'));
    console.log('PASS: navigation, escaped text preview, truncation notice, attach file, parent navigation');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
