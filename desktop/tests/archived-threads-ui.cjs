const { chromium } = require('playwright');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  try {
    const page = await browser.newPage();
    await page.addInitScript(() => {
      window.__fail = true; window.__calls = [];
      localStorage.setItem('felix-audit-log-v1', '[]');
      localStorage.setItem('codex-desktop-state-v1', JSON.stringify({ model: 'test', threads: [{ id: 'saved', remoteId: 'saved', title: 'Saved', archived: true, messages: [{ id: 'msg', role: 'user', content: 'Keep this', createdAt: new Date().toISOString() }], updatedAt: new Date().toISOString() }, { id: 'stale', remoteId: 'remote', title: 'Local title', archived: false, messages: [], updatedAt: new Date().toISOString() }] }));
      window.desktop = { listModels: async () => ({ ok: true, models: ['test'] }) };
      window.codex = { connect: async () => ({ ok: true }), request: async (method, params) => {
        window.__calls.push({ method, params });
        if(method==='thread/search'&&window.__brokenSearch)return {ok:true,result:{data:[{thread:{id:'saved',name:'Saved'},snippet:'valid'},{thread:{id:window.__brokenSearch},snippet:'broken'}]}};
        if (method === 'thread/list' && params.archived && window.__brokenPage) return { ok: true, result: { data: [], nextCursor: {} } };
        if(method==='thread/search'&&params.searchTerm==='slow')return new Promise(resolve=>{window.__slow=()=>resolve({ok:true,result:{data:[{thread:{id:'late',name:'Late archive'},snippet:'slow content'}]}});});
        if(method==='thread/search'&&params.searchTerm==='cycle')return {ok:true,result:{data:[{thread:{id:'cycle',name:'Cycle archive'},snippet:'cycle content'}],nextCursor:params.cursor==='A'?'B':'A'}};
        if (method === 'thread/search') return {ok:true,result:{data:[{thread:{id:'saved',name:'Saved'},snippet:'Keep this archived content'}]}};
        if (method === 'thread/unarchive' && window.__fail) return { ok: false, error: 'Restore failed' };
        if (method === 'thread/list' && params.archived) return { ok: true, result: params.cursor ? { data: [null, { id: 'older', name: {}, preview: 'Older', cwd: { invalid: true } }] } : { data: [{ id: 'saved', name: 'Saved' }, { id: 'remote', name: 'Remote' }], nextCursor: 'more' } };
        return { ok: true, result: { data: [] } };
      }, notify: async () => ({}), onNotification: () => () => {}, onServerRequest: () => () => {}, onClosed: () => () => {}, onError: () => () => {}, onStderr: () => () => {} };
    });
    await page.goto(process.env.FELIX_TEST_URL || 'http://127.0.0.1:5318');
    await page.getByRole('button', { name: '归档会话', exact: true }).click();
    await page.getByRole('textbox',{name:'搜索归档内容',exact:true}).fill('slow');
    await page.getByRole('button',{name:'搜索归档',exact:true}).click();
    await page.waitForFunction(()=>Boolean(window.__slow));
    await page.getByRole('button',{name:'清除归档搜索',exact:true}).click();
    await page.evaluate(()=>window.__slow());
    assert.equal(await page.getByRole('button',{name:'恢复 Late archive',exact:true}).count(),0);
    await page.getByRole('textbox',{name:'搜索归档内容',exact:true}).fill('cycle');
    await page.getByRole('button',{name:'搜索归档',exact:true}).click();
    await page.getByText('cycle content',{exact:true}).waitFor();
    await page.getByRole('button',{name:'加载更多归档',exact:true}).click();
    await page.getByRole('button',{name:'加载更多归档',exact:true}).click();
    await page.getByRole('alert').filter({hasText:'归档分页游标重复'}).waitFor();
    await page.getByRole('textbox',{name:'搜索归档内容',exact:true}).fill('Keep this');
    await page.getByRole('button',{name:'搜索归档',exact:true}).click();
    await page.getByText('Keep this archived content',{exact:true}).waitFor();
    assert.ok(await page.evaluate(()=>window.__calls.some(item=>item.method==='thread/search'&&item.params.archived===true)));
    assert.equal(await page.getByRole('button',{name:'恢复 Local title',exact:true}).count(),0);
    for(const badId of [7,' ']) {
      await page.evaluate(id=>{window.__brokenSearch=id;},badId);
      await page.getByRole('button',{name:'刷新归档',exact:true}).click();
      await page.getByRole('alert').filter({hasText:'会话搜索结果无效'}).waitFor();
      await page.getByText('Keep this archived content',{exact:true}).waitFor();
      assert.equal(await page.getByText('broken',{exact:true}).count(),0);
    }
    await page.evaluate(()=>{window.__brokenSearch=false;});
    await page.getByRole('button',{name:'刷新归档',exact:true}).click();
    await page.getByRole('alert').waitFor({state:'hidden'});
    await page.getByText('Keep this archived content',{exact:true}).waitFor();
    await page.getByRole('button',{name:'清除归档搜索',exact:true}).click();
    await page.getByRole('button', { name: '加载更多归档' }).click();
    await page.getByRole('button', { name: '恢复 Older' }).waitFor();
    await page.evaluate(() => { window.__brokenPage = true; });
    await page.getByRole('button', { name: '刷新归档' }).click();
    await page.getByRole('alert').filter({ hasText: '会话列表格式无效' }).waitFor();
    assert.equal(await page.getByRole('button', { name: '恢复 Older' }).count(), 1);
    await page.evaluate(() => { window.__brokenPage = false; });
    await page.getByRole('button', { name: '刷新归档' }).click();
    await page.getByRole('alert').waitFor({ state: 'hidden' });
    await page.getByRole('button', { name: '恢复 Saved' }).click();
    await page.getByRole('alert').filter({ hasText: 'Restore failed' }).waitFor();
    assert.equal(await page.getByRole('button', { name: '恢复 Saved' }).count(), 1);
    await page.evaluate(() => { window.__fail = false; });
    await page.getByRole('button', { name: '恢复 Saved' }).click();
    await page.getByRole('button', { name: '恢复 Saved' }).waitFor({ state: 'detached' });
    await page.getByRole('button', { name: '恢复 Local title' }).click();
    await page.getByRole('button', { name: '恢复 Local title' }).waitFor({ state: 'detached' });
    await page.getByRole('button', { name: '关闭归档会话' }).click();
    await page.getByRole('button', { name: 'Saved', exact: true }).waitFor();
    await page.getByRole('button', { name: 'Local title', exact: true }).waitFor();
    assert.ok(await page.evaluate(() => JSON.parse(localStorage.getItem('felix-audit-log-v1')).some(item => item.action === '恢复归档会话')));
    const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('codex-desktop-state-v1')).threads.find(thread => thread.id === 'saved'));
    assert.equal(saved.messages[0].content, 'Keep this');
    assert.equal(saved.archived, false);
    console.log('PASS: archived pagination, restore retry, deduplication and local history preservation');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
